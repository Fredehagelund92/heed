/**
 * Loads a binding on its first call, so neither the mock nor the http client is part of the
 * first load. Every call after that goes straight to the loaded binding.
 */
function lazy(load: () => Promise<ContextApi>): ContextApi {
  let binding: Promise<ContextApi> | undefined
  const get = () => (binding ??= load())
  // Every method takes plain arguments and returns a promise, so forwarding keeps its type.
  const forward = <K extends keyof ContextApi>(name: K) =>
    (async (...args: unknown[]) => {
      const binding = await get()
      return (binding[name] as (...args: unknown[]) => Promise<unknown>)(...args)
    }) as ContextApi[K]
  return Object.fromEntries(
    contextApiMethods.map((name) => [name, forward(name)]),
  ) as unknown as ContextApi
}

/**
 * The API the app talks to. `VITE_API_MODE=http` talks to the Heed service at `/api/v1` on the
 * page's own origin (the dev server proxies it, see vite.config.ts). Anything else uses the mock,
 * as Storybook, unit tests and screenshots do, so they stay deterministic.
 */
export const api: ContextApi =
  import.meta.env.VITE_API_MODE === 'http'
    ? lazy(async () => {
        const [{ createHttpApi }, { browserPersonalLists }, { API_PREFIX }] = await Promise.all([
          import('./http-api'),
          import('./personal'),
          import('../../contract/limits.ts'),
        ])
        return createHttpApi({
          baseUrl: new URL(API_PREFIX, window.location.origin).href,
          personal: browserPersonalLists('cl.'),
        })
      })
    : lazy(async () => (await import('./mock-api')).mockApi)
