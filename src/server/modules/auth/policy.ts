/** Unknown operations fail closed, including new contract operations awaiting a policy. */
export function can(principal: Principal | null, operation: string): boolean {
  const policy = policies[operation as keyof typeof policies]
  if (policy === 'public') return true
  if (!principal) return false
  const roles = principal.permissions.roles
  return (
    policy === 'read' ||
    policy === 'propose' ||
    (policy === 'admin' && roles.includes('administrator')) ||
    // FR-808: administrators and auditors search and export the history log.
    (policy === 'audit' && (roles.includes('administrator') || roles.includes('auditor'))) ||
    // Test results, the Quality page, editions and area dashboards: administrators (the data
    // platform team for the first release), and owners (the service narrows to
    // their areas).
    (policy === 'maintain' &&
      (roles.includes('administrator') ||
        principal.permissions.assignments.some((a) => a.role === 'owner')))
  )
}
